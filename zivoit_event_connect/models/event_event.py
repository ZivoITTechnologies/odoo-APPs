def _parse_networks(text):
    networks = []
    for raw in (text or '').replace(',', '\n').replace(';', '\n').splitlines():
        raw = raw.strip()
        if not raw or raw.startswith('#'):
            continue
        networks.append(ipaddress.ip_network(raw, strict=False))
    return networks


