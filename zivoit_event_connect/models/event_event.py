    @api.depends('name')
    def _compute_zivo_slug(self):
        for event in self:
            event.zivo_slug = '%s-%s' % (self.env['ir.http']._slugify(event.name or 'event'), event.id or 0)

    @api.depends('zivo_invitation_ids', 'zivo_document_ids', 'zivo_booking_ids')
    def _compute_zivo_counts(self):
        for event in self:
            event.zivo_invitation_count = len(event.zivo_invitation_ids)
            event.zivo_document_count = len(event.zivo_document_ids)
            event.zivo_booking_count = len(event.zivo_booking_ids)

    def _compute_zivo_audit_count(self):
        data = dict(self.env['zivo.audit.log'].sudo()._read_group(
            [('model', '=', 'event.event'), ('res_id', 'in', self.ids)], ['res_id'], ['__count']))
        for event in self:
            event.zivo_audit_count = data.get(event.id, 0)

    @api.constrains('zivo_ip_ranges', 'zivo_access_mode')
    def _check_zivo_ip_ranges(self):
        for event in self:
            try:
                networks = _parse_networks(event.zivo_ip_ranges)
            except ValueError as exc:
                raise ValidationError(self.env._('Invalid IP range on event "%(event)s": %(error)s',
                                                 event=event.name, error=exc))
            if event.zivo_access_mode == 'ip' and not networks:
                raise ValidationError(self.env._('Please define at least one allowed IP range for "%s".', event.name))

    # ------------------------------------------------------------------
    # Access evaluation
    # ------------------------------------------------------------------
    def _zivo_ip_allowed(self, ip):
        self.ensure_one()
        if not ip:
            return False
        try:
            address = ipaddress.ip_address(ip)
        except ValueError:
            return False
        for network in _parse_networks(self.zivo_ip_ranges):
            if address.version == network.version and address in network:
                return True
        return False

    @api.model
    def _zivo_request_context(self):
        """Information about the current website visitor used to evaluate access rules."""
        ctx = {'ip': False, 'tokens': [], 'partner': self.env.user.partner_id, 'is_public': self.env.user._is_public()}
        try:
            if request and request.httprequest:
                ctx['ip'] = request.httprequest.remote_addr
                ctx['tokens'] = list(request.session.get(SESSION_INVITE_KEY) or [])
        except RuntimeError:
            pass
        ctx['ip'] = self.env.context.get('zivo_remote_ip', ctx['ip'])
        if 'zivo_invite_tokens' in self.env.context:
            ctx['tokens'] = self.env.context['zivo_invite_tokens']
        return ctx

    def _zivo_has_access(self, req_ctx=None):
        """Return True when the current visitor satisfies the event access rule."""
        self.ensure_one()
        if self.zivo_access_mode in (False, 'open'):
            return True
        user = self.env.user
        if not user._is_public() and user.has_group('event.group_event_user'):
            return True  # event staff can always preview
        req_ctx = req_ctx or self._zivo_request_context()
        event_sudo = self.sudo()
        if self.zivo_access_mode == 'ip':
            return event_sudo._zivo_ip_allowed(req_ctx['ip'])
        # invitation only
        invitations = event_sudo.zivo_invitation_ids.filtered(lambda i: i.state != 'revoked')
        if req_ctx['tokens'] and invitations.filtered(lambda i: i.token in req_ctx['tokens']):
            return True
        if not req_ctx['is_public']:
            partner = req_ctx['partner']
            if invitations.filtered(lambda i: i.partner_id == partner or
                                    (i.email and partner.email and i.email.lower() == partner.email.lower())):
                return True
            if event_sudo.registration_ids.filtered(lambda r: r.partner_id == partner and r.state != 'cancel'):
                return True
        return False

    @api.depends_context('uid')
    @api.depends('website_visibility', 'is_participating', 'zivo_access_mode')
    def _compute_is_visible_on_website(self):
        super()._compute_is_visible_on_website()
        restricted = self.filtered(lambda e: e.zivo_access_mode not in (False, 'open') and e.is_visible_on_website)
        if restricted:
            req_ctx = self._zivo_request_context()
            for event in restricted:
                event.is_visible_on_website = event._zivo_has_access(req_ctx)

    @api.model
    def _zivo_allowed_restricted_ids(self):
        restricted = self.sudo().with_context(active_test=True).search([('zivo_access_mode', 'not in', ('open', False))])
        if not restricted:
            return []
        req_ctx = self._zivo_request_context()
        return [ev.id for ev in restricted if ev.with_env(self.env)._zivo_has_access(req_ctx)]

    @api.model
    def _search_is_visible_on_website(self, operator, value):
        domain = super()._search_is_visible_on_website(operator, value)
        if domain is NotImplemented:
            return domain
        allowed = self._zivo_allowed_restricted_ids()
        return ['&', '|', ('zivo_access_mode', 'in', ('open', False)), ('id', 'in', allowed)] + list(domain)

    @api.model
    def _zivo_department_domain(self, value):
        """Domain for a department filter given as comma separated codes and/or ids."""
        if not value:
            return []
        ids, codes = [], []
        for part in str(value).split(','):
            part = part.strip()
            if not part:
                continue
            (ids if part.isdigit() else codes).append(int(part) if part.isdigit() else part)
        depts = self.env['zivo.event.department'].sudo().search(
            ['|', ('id', 'in', ids), ('code', 'in', codes)]) if (ids or codes) else self.env['zivo.event.department']
        if not depts:
            return [('id', 'in', [])]  # unknown department: match nothing
        # include sub-departments
        depts = self.env['zivo.event.department'].sudo().search([('id', 'child_of', depts.ids)])
        return [('zivo_department_ids', 'in', depts.ids)]

    @api.model
    def _search_get_detail(self, website, order, options):
        result = super()._search_get_detail(website, order, options)
        dept_domain = self._zivo_department_domain(options.get('zivo_department'))
        if dept_domain:
            for key in ('base_domain', 'no_date_domain', 'no_country_domain'):
                if key in result:
                    result[key] = list(result[key]) + [dept_domain]
        return result

    # ------------------------------------------------------------------
    # API serialisation
    # ------------------------------------------------------------------
    def _zivo_dt(self, value):
        if not value:
            return None
        return pytz.utc.localize(value).isoformat()

    def _zivo_dt_local(self, value):
        self.ensure_one()
        if not value:
            return None
        tz = pytz.timezone(self.date_tz or 'UTC')
        return pytz.utc.localize(value).astimezone(tz).isoformat()

