    _zivo_ai_search_cache = {}

    @api.model
    def _zivo_ai_interpret_query(self, query):
        """Turn a visitor sentence into API filters. Falls back to a keyword search when AI is off."""
        query = (query or '').strip()[:300]
        today = fields.Date.context_today(self)
        fallback = {'q': query, 'source': 'keyword'}
        if not query or not self.env['zivo.ai.service']._feature_enabled('search'):
            return fallback
        cache_key = (self.env.cr.dbname, query.lower(), str(today))
        if cache_key in self._zivo_ai_search_cache:
            return dict(self._zivo_ai_search_cache[cache_key])
        depts = self.env['zivo.event.department'].sudo().search([])
        tags = self.env['event.tag'].sudo().search([])
        types = self.env['event.type'].sudo().search([])
        cities = sorted(set(filter(None, self.sudo().search([('address_id', '!=', False)]).mapped('address_id.city'))))
        prompt = (
            'Today is %s (%s). Convert the website visitor search into filters.\n'
            'Search: "%s"\n'
            'Known department codes: %s\nKnown tags: %s\nKnown event types: %s\nKnown cities: %s\n'
            'Return JSON: {"keywords": str|null (only words that must match the event title), '
            '"departments": [department codes], "tags": [tag names], "event_type": str|null, '
            '"date_from": "YYYY-MM-DD"|null, "date_to": "YYYY-MM-DD"|null, "city": str|null, '
            '"online": true|false|null}. Use only known values; resolve relative dates (next month, this weekend).'
        ) % (today, today.strftime('%A'), query, ', '.join('%s (%s)' % (d.code, d.name) for d in depts),
             ', '.join(tags.mapped('name')), ', '.join(types.mapped('name')), ', '.join(cities[:100]))
        try:
            data = self.env['zivo.ai.service']._zivo_ai_complete(
                'search', 'You translate event search sentences into structured filters.', prompt, as_json=True)
        except Exception:  # noqa: BLE001 - never break the website search
            return fallback
        result = {'source': 'ai'}
        if data.get('keywords'):
            result['q'] = str(data['keywords'])[:100]
        codes = [c for c in (data.get('departments') or []) if c in depts.mapped('code')]
        if codes:
            result['department'] = ','.join(codes)
        tag_ids = tags.filtered(lambda t: t.name.lower() in [str(n).lower() for n in (data.get('tags') or [])]).ids
        if tag_ids:
            result['tag'] = ','.join(map(str, tag_ids))
        etype = types.filtered(lambda t: data.get('event_type') and t.name.lower() == str(data['event_type']).lower())
        if etype:
            result['type'] = str(etype[0].id)
        for src, dst in (('date_from', 'from'), ('date_to', 'to')):
            value = data.get(src)
            if value and re.match(r'^\d{4}-\d{2}-\d{2}$', str(value)):
                result[dst] = str(value)
        if data.get('city'):
            result['city'] = str(data['city'])[:80]
        if data.get('online') in (True, False):
            result['online'] = '1' if data['online'] else '0'
        if len(self._zivo_ai_search_cache) > 500:
            self._zivo_ai_search_cache.clear()
        self._zivo_ai_search_cache[cache_key] = dict(result)
        return result

    def action_zivo_push_webhooks(self):
        """Manually re-push the event to every webhook (e.g. after a website rebuild)."""
        self.env['zivo.webhook']._zivo_enqueue('event.updated', self._zivo_webhook_candidates())
        return {
            'type': 'ir.actions.client', 'tag': 'display_notification',
            'params': {'type': 'success', 'message': self.env._('Webhook deliveries queued.'), 'sticky': False},
        }
